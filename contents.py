def get_caption_for_photo(phone: str, instagram: str, channel_link: str) -> str:
    """کپشن کوتاه‌تر برای عکس‌های ارسالی کاربر"""
    lines = [
        "🛏️ سرویس خواب سوین چوب",
        "کیفیت کارخانه‌ای | فروش عمده و خرده",
        "",
        f"📞 {phone}",
        f"📷 {instagram}",
        f"🔗 {channel_link}",
    ]
    return "\n".join(lines)
